"""Run every named query in sql/03_queries.sql and write results (with the SQL) to Markdown.

Usage: python -m database.scripts.run_sql_queries
"""
from __future__ import annotations

import re

import pandas as pd
import pymysql

from database import config as C


def parse_queries(text: str):
    blocks = re.split(r"(?m)^-- name:\s*", text)[1:]
    for b in blocks:
        name, rest = b.split("\n", 1)
        desc = re.search(r"-- desc:\s*(.*)", rest).group(1).strip()
        sql = "\n".join(l for l in rest.split("\n") if not l.startswith("-- desc:")).strip().rstrip(";")
        sql = re.sub(r"(?m)^--.*$", "", sql).strip()
        yield name.strip(), desc, sql


def main():
    conn = pymysql.connect(host=C.MYSQL_HOST, port=C.MYSQL_PORT, user=C.MYSQL_USER, password=C.MYSQL_PASSWORD,
                           database=C.MYSQL_DATABASE, charset="utf8mb4")
    out = ["# SQL query results\n", f"_Database: `{C.MYSQL_DATABASE}` on MySQL-compatible server "
           f"{conn.get_server_info()}. Generated by `python -m database.scripts.run_sql_queries`._\n"]
    for name, desc, sql in parse_queries((C.SQL_DIR / "03_queries.sql").read_text(encoding="utf-8")):
        df = pd.read_sql(sql, conn)
        print(f"{name}: {len(df)} rows")
        out += [f"\n## {name}\n", f"{desc}\n", "```sql\n" + sql + ";\n```\n", f"Result ({len(df)} rows):\n",
                df.to_markdown(index=False) + "\n"]
    C.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (C.RESULTS_DIR / "sql_query_results.md").write_text("\n".join(out), encoding="utf-8")
    conn.close()


if __name__ == "__main__":
    main()
