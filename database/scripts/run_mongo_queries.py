"""Run the MongoDB query catalogue, print results and write them to Markdown.

Usage: python -m database.scripts.run_mongo_queries
"""
from __future__ import annotations

import json

import pandas as pd
from bson import json_util
from pymongo import MongoClient

from database import config as C
from database.mongo.queries import QUERIES


def run_query(db, q) -> list[dict]:
    col = db[q["collection"]]
    if q["op"] == "find":
        cur = col.find(q.get("filter", {}), q.get("projection"))
        if q.get("sort"):
            cur = cur.sort(q["sort"])
        if q.get("limit"):
            cur = cur.limit(q["limit"])
        return list(cur)
    return list(col.aggregate(q["pipeline"]))


def pipeline_json(q) -> str:
    if q["op"] == "find":
        body = {"filter": q.get("filter", {}), "projection": q.get("projection"), "sort": dict(q.get("sort", [])), "limit": q.get("limit")}
        body = {k: v for k, v in body.items() if v}
    else:
        body = q["pipeline"]
    return json_util.dumps(body, indent=2, json_options=json_util.RELAXED_JSON_OPTIONS)


def main():
    db = MongoClient(C.MONGO_URI)[C.MONGO_DB]
    info = MongoClient(C.MONGO_URI).server_info()
    out = ["# MongoDB query results\n", f"_Database: `{C.MONGO_DB}`, server {info.get('version')}. "
           "Generated by `python -m database.scripts.run_mongo_queries`._\n"]
    for q in QUERIES:
        rows = run_query(db, q)
        print(f"{q['name']}: {len(rows)} docs")
        flat = pd.json_normalize(json.loads(json_util.dumps(rows, json_options=json_util.RELAXED_JSON_OPTIONS)))
        for c in flat.columns:   # {"$date": ...} -> readable
            if c.endswith("$date"):
                flat = flat.rename(columns={c: c.replace(".$date", "")})
                flat[c.replace(".$date", "")] = flat[c.replace(".$date", "")].astype(str).str.replace("T", " ").str.replace("Z", "", regex=False).str.replace(r"\.000$", "", regex=True)
        for c in ("_id.$oid", "_id"):
            if c in flat.columns and q["name"] == "M1_latest_reading":
                pass
        result_block = flat.to_markdown(index=False) + "\n"
        if q["name"].startswith("M1"):      # one wide nested document: JSON reads better than a 19-column table
            result_block = "```json\n" + json_util.dumps(rows[0], indent=2, json_options=json_util.RELAXED_JSON_OPTIONS) + "\n```\n"
        coll_op = (f"db.{q['collection']}.find(...)" if q["op"] == "find" else f"db.{q['collection']}.aggregate(pipeline)")
        out += [f"\n## {q['name']}\n", f"{q['desc']}\n", f"`{coll_op}`\n", "```json\n" + pipeline_json(q) + "\n```\n",
                f"Result ({len(rows)} documents):\n", result_block]
    (C.RESULTS_DIR / "mongo_query_results.md").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
